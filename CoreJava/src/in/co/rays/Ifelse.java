package in.co.rays;

public class Ifelse {
	public static void main(String[] args) {
		int money = 99;
		if (money > 100) {
			System.out.println("Wow! I can buy a pizza");
		} else if (money > 95) {
			System.out.println("I can buy burger");
		} else {
			System.out.println("OH! I cannot buy pizza");
		}
	}
}
