package in.note.learn.stringclass;

public class MathMethodPractice {
    public static void main(String[] args) {
    	System.out.println("Mathematical functions");
    	
    	System.out.println("Maximum from 20,25 is- "+Math.max(20, 25));
    	
    	System.out.println("Minimum from 20,25 is- "+Math.min(20, 25));
    	
    	System.out.println("Absolute value of -7 "+Math.abs(-7));
    	
    	System.out.println("Expoliate of 10- "+Math.exp(10));
    	
    	System.out.println("Random number- "+(int)(Math.random()*100));
    	
    	System.out.println("Square root- "+(int)(Math.sqrt(25)));
    	
    }
}

