package in.com.java.autoboxing.unboxing;

public class TestAutoboxing {
	// Auto boxing is the automatic conversion of primitive data type into its
	// corresponding wrapper class

	public static void main(String[] args) {

		int i = 5; // int is primitive data type
		Integer b = i; // Integer is a wrapper class of int
		System.out.println(b); // autoboxing
	}

}
