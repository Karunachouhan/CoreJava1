package in.com.java.autoboxing.unboxing;

public class TestUnboxing {
	// Unboxing is a automatic conversion of wrapper class into its corresponding
	// primitive data type

	public static void main(String[] args) {

		Integer i = 23; // Wrapper class
		int j = i; // Primitive data type

		System.out.println(j); // unboxing
	}

}
